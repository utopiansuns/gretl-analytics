def _dist_label(dist):
    if not dist:
        return ""
    d = dist.get("dist")
    df = dist.get("df", ())
    if d == "F":
        return f"F({df[0]}, {df[1]})"
    if d == "chi2":
        return f"χ²({df[0]})"
    if d == "t":
        return f"t({df[0]})"
    if d == "N":
        return "N(0,1)"
    if d == "tau":
        return dist.get("label", "τ").replace("tau", "τ")
    return ""


def _crit(dist, alpha=0.05):
    if not dist:
        return None
    d, df = dist.get("dist"), dist.get("df", ())
    try:
        if d == "F":
            return stats.f_crit(alpha, *df)
        if d == "chi2":
            return stats.chi2_crit(alpha, df[0])
    except Exception:
        return None
    return None


def parse_extra(key, text):
    """Дополнительные сведения из текста Gretl для отдельных тестов."""
    ex = {}
    if key == "chow":
        m = re.search(r"structural break at observation (\S+)", text)
        if m:
            ex["break"] = m.group(1)
        m = re.search(r"Chow test for (?:structural difference|difference) with respect to (\S+)", text)
        if m:
            ex["dummy"] = m.group(1)
    if key == "qlr":
        m = re.search(r"(?:maximum|Maximum) F\(.*?\) = ([\d.]+) occurs at observation (\S+)", text)
        if m:
            ex["break"] = m.group(2)
    if key in ("omit", "add"):
        m = re.search(r"for the variables\s*\n?\s*(.+?)\n", text, re.S)
        if m:
            ex["vars"] = m.group(1).strip()
        m = re.search(r"(?:Omitting|Adding) variables improved (\d) of (\d) information criteria", text)
        if m:
            ex["ic"] = (int(m.group(1)), int(m.group(2)))
        m = re.search(r"Test statistic: (F\(\d+, \d+\)|Chi-square\(\d+\)) = ([\d.e+-]+), p-value ([\d.e+-]+)", text)
        if m:
            ex["text_stat"] = (m.group(1), float(m.group(2)), float(m.group(3)))
    if key == "autocorr":
        m = re.search(r"autocorrelation up to order (\d+)", text)
        if m:
            ex["order"] = int(m.group(1))
    if key == "adf":
        m = re.search(r"estimated value of \(a - 1\): ([-\d.e]+)", text)
        ms = re.findall(r"(test with constant|with constant and trend|test without constant)", text)
        if ms:
            ex["variants"] = ms
    if key == "kpss":
        m = re.search(r"Test statistic: ([\d.]+)", text)
        if m:
            ex["stat"] = float(m.group(1))
        m = re.search(r"Critical values:\s*([\d.%\s]+)", text)
        m2 = re.findall(r"(\d+)%\s+([\d.]+)", text)
        if m2:
            ex["crit"] = {int(a): float(b) for a, b in m2}
        m3 = re.search(r"P-value (<|>|=) ([\d.]+)", text, re.I)
        if m3:
            ex["pnote"] = (m3.group(1), float(m3.group(2)))
    if key == "cusum":
        m = re.search(r"Harvey-Collier t\((\d+)\) = ([-\d.]+) with p-value ([\d.e-]+)", text)
        if m:
            ex["hc"] = (int(m.group(1)), float(m.group(2)), float(m.group(3)))
    return ex


def parse_vif(text):
    vals = []
    for line in text.split("\n"):
        m = re.match(r"^\s+(\S+)\s+([\d.]+)\s*$", line)
        if m:
            vals.append((m.group(1), float(m.group(2))))
    return vals


def interpret_test(ctx, key, stat, p, dist, text, model_ref=None, full=True, alpha=0.05):
    """Возвращает (заголовок, таблица, абзацы)."""
    if key == "vif":
        return _interpret_vif(ctx, text, model_ref, full)
    kb = KB.get(key)
    if not kb:
        return (f"Результат команды {key}", None,
                ["Для этого теста помощник приводит исходный вывод Gretl без автоматической интерпретации."])
    name, h0, h1, rej, notrej, conseq = kb
    ex = parse_extra(key, text)
    dl = ctx.raw(_dist_label(dist))
    P = []
    if key in ("omit", "add") and "text_stat" in ex and (stat is None or not fmt.is_num(stat)):
        stat, p = ex["text_stat"][1], ex["text_stat"][2]
    if stat is None or not fmt.is_num(stat):
        return name, None, ["Gretl не вернул численное значение статистики для этого теста; см. исходный вывод."]
    if key == "kpss" and (p is None or not fmt.is_num(p)):
        p = None
    reject = p is not None and fmt.is_num(p) and p < alpha
    where = ""
    if key == "chow" and ex.get("break"):
        where = f" (точка разбиения – наблюдение {ctx.raw(ex['break'])})"
    if key == "chow" and ex.get("dummy"):
        where = f" (группы задаются фиктивной переменной {ex['dummy']})"
    if key == "autocorr" and ex.get("order"):
        where = f" (до порядка {ctx.int(ex['order'])})"
    if key in ("omit", "add") and ex.get("vars"):
        where = f" ({ex['vars']})"
    stat_s = f"{dl + ' = ' if dl else 'статистика = '}{ctx.n(stat, sig=6)}"
    p_s = ctx.p(p) if p is not None else "p-значение Gretl не сообщает"
    if ex.get("pnote"):   # KPSS: Gretl сообщает только границу, например «P-value < .01»
        sign, bound = ex["pnote"]
        p_s = f"p {sign} {ctx.n(bound, nd=2)}"
        p = bound / 2 if sign == "<" else (bound if sign == "=" else max(bound, 0.5))
    P.append(f"{name}{where}. Нулевая гипотеза H0: {h0}; альтернатива H1: {h1}.")
    line = f"Результат: {stat_s}, {p_s}."
    if full:
        c = _crit(dist, alpha)
        if c is not None:
            line += (f" Критическое значение при α = 5%: {ctx.n(c, sig=4)}; наблюдаемое значение "
                     f"{'больше' if stat > c else 'меньше'} критического.")
    P.append(line)
    if key == "kpss" and ex.get("crit"):
        cv = ex["crit"].get(5)
        if cv:
            reject = stat > cv
            P.append(f"Критическое значение KPSS при 5%: {ctx.n(cv, sig=4)}.")
    if key == "adf" and p is not None:
        pass
    decision = (f"Поскольку {'p-значение меньше 0,05' if p is not None else 'статистика превышает критическое значение'}, "
                f"H0 отвергается на 5%-ном уровне: {rej}." if reject else
                f"Поскольку {'p-значение больше 0,05' if p is not None else 'статистика не превышает критического значения'}, "
                f"H0 не отвергается на 5%-ном уровне: {notrej}.")
    P.append(decision)
    if reject and conseq and full:
        P.append("Последствия: " + conseq)
    if not reject and full and key in ("white", "bp", "koenker", "white_nocross", "autocorr", "normality", "reset"):
        P.append("Важно: неотклонение H0 не доказывает её истинность – данные лишь не противоречат ей "
                 "(особенно при малом объёме выборки мощность теста невелика).")
    if key in ("omit", "add") and ex.get("ic") and full:
        a, b = ex["ic"]
        verb = "исключение" if key == "omit" else "добавление"
        P.append(f"По сообщению Gretl, {verb} переменных улучшило {ctx.int(a)} из {ctx.int(b)} информационных критериев "
                 f"(Акаике, Шварца, Хеннана–Куинна).")
    if key == "chow" and full:
        P.append("Тест Чоу корректен при гомоскедастичных и неавтокоррелированных ошибках; при их нарушении "
                 "предпочтительна робастная версия или тест QLR.")
    if key == "cusum" and ex.get("hc"):
        d, tv, pv = ex["hc"]
        P.append(f"Статистика Харви–Коллиера t({ctx.int(d)}) = {ctx.n(tv, sig=4)}, {ctx.p(pv)}.")
    if key == "adf" and full:
        P.append("Если ряд нестационарен, регрессии в уровнях могут быть ложными (spurious regression); "
                 "обычно переходят к разностям или проверяют коинтеграцию.")
    table = {"header": ["Показатель", "Значение"],
             "rows": [["Статистика" + (f" {dl}" if dl else ""), fmt.g(stat)],
                      ["p-значение", fmt.pval(p, table=False) if p is not None else "-"]]}
    return name, table, P


