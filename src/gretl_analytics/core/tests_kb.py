    if not vals:
        return "Факторы инфляции дисперсии (VIF)", None, ["Gretl не вывел значения VIF для этой модели."]
    hi = [(n, v) for n, v in vals if v > 10]
    mid = [(n, v) for n, v in vals if 5 < v <= 10]
    mx = max(vals, key=lambda x: x[1])
    P = [f"VIF показывает, во сколько раз дисперсия оценки коэффициента увеличена из-за линейной связи регрессора с остальными: "
         f"VIF_j = 1/(1 − R_j²). Максимальное значение: {ctx.n(mx[1], sig=4)} ({mx[0]})."]
    names = {n for n, _ in vals}
    poly = [n for n, v in hi if (n.startswith("sq_") and n[3:] in names) or ("sq_" + n) in names]
    if hi:
        P.append("Значения больше 10 (" + ", ".join(f"{n}: {ctx.n(v, sig=4)}" for n, v in hi) +
                 ") указывают на серьёзную мультиколлинеарность: оценки этих коэффициентов неустойчивы, а их стандартные ошибки завышены.")
        if poly:
            P.append("Для пары «переменная – её квадрат» (" + ", ".join(poly) + ") высокий VIF ожидаем по построению и сам по себе не является "
                     "проблемой: значимость нелинейного эффекта следует проверять совместным F-тестом для обоих слагаемых "
                     "(Тесты → Убрать избыточные переменные).")
    elif mid:
        P.append("Умеренно повышенные значения (5–10: " + ", ".join(f"{n}: {ctx.n(v, sig=4)}" for n, v in mid) +
                 ") требуют осторожности при интерпретации отдельных коэффициентов; критический порог 10 не превышен.")
    else:
        P.append("Все значения VIF меньше 5: признаков существенной мультиколлинеарности нет.")
    table = {"header": ["Переменная", "VIF"], "rows": [[n, fmt.g(v, 4)] for n, v in vals]}
    return "Факторы инфляции дисперсии (VIF)", table, P
